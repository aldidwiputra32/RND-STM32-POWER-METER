void integerToArray(uint8_t data, uint8_t * buffer){
    uint8_t dataBuffer;
    for(uint8_t indeks=0;indeks<8;indeks++){
        dataBuffer = (data>>indeks) & 0b0000001;
        buffer[indeks] = dataBuffer;
    }
}
